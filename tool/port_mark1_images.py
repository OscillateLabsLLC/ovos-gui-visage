"""Port the Mark 1 firmware's mouth bitmaps into Dart row bitmasks.

Reads mouth_images.py from ovos-virtual-mark1 (itself generated from MycroftAI/enclosure-mark1 by its
scripts/port_firmware_tables.py), decodes the 8x8 plates (16 nibbles each, column-major, bit 0 = top pixel) into
32 x 8 frames, and writes lib/face/mark1_images.g.dart: each frame is eight ints, bit x of row y set when the LED at
column x, row y is lit (column 0 on the viewer's left).

usage: python3 tool/port_mark1_images.py /path/to/ovos_virtual_mark1/mouth_images.py
"""
import runpy
import sys
from pathlib import Path

PLATE = 8
PLATES = 4
NIBBLE_ROWS = 4
OUT = Path(__file__).resolve().parent.parent / "lib" / "face" / "mark1_images.g.dart"
TABLES = [("listenFrames", "LISTEN_ANIMATION"), ("talkFrames", "TALK_ANIMATION"), ("thinkFrames", "THINK_ANIMATION"),
          ("visemeFrames", "MOUTH_VISEMES")]


def decode_frame(plates):
    rows = [0] * PLATE
    for p, nibbles in enumerate(plates):
        for column in range(PLATE):
            for row in range(PLATE):
                word = nibbles[2 * column + row // NIBBLE_ROWS]
                if (word >> (row % NIBBLE_ROWS)) & 1:
                    rows[row] |= 1 << (p * PLATE + column)
    return rows


def frames(table):
    assert len(table) % PLATES == 0, len(table)
    return [decode_frame(table[i:i + PLATES]) for i in range(0, len(table), PLATES)]


def main():
    source = runpy.run_path(sys.argv[1])
    lines = ["// Generated by tool/port_mark1_images.py from the Mark 1 firmware's mouth bitmaps. Do not edit.",
             "//", "// Each frame is eight rows of the 32 x 8 mouth; bit x of a row is the LED in column x (0 = viewer's left).", ""]
    for dart_name, py_name in TABLES:
        lines.append(f"const {dart_name} = <List<int>>[")
        for frame in frames(source[py_name]):
            lines.append("  [" + ", ".join(f"0x{row:08X}" for row in frame) + "],")
        lines.append("];")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
